"""Generate the M5 full-benchmark YAMLs (§4.11, second amendment).

Emits 6 batches into this directory: for each topology (C16, P16, Z12) a main
sweep (5 arms, every pigeonhole-eligible graph: n <= qubit count) and a layout
supplement (minorminer-layout on the n <= 1000 subset — the CLI has no watchdog
and p-norm layout on multi-thousand-node sources can stall workers well past the
cooperative budget; the restriction is documented in the batch note).

Run: .venv/bin/python docs/paper3/experiments/gen_m5_full.py
Deterministic: reads only the packaged manifest.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
MANIFEST = os.path.join(HERE, "../../../packages/ember-qc/src/ember_qc/graphs/manifest.json")

TOPOS = {  # registry name -> (tag, qubit count)
    "chimera_16x16x4": ("c16", 2048),
    "pegasus_16": ("p16", 5640),
    "zephyr_12": ("z12", 4800),
}
MAIN_ARMS = ["minorminer", "p3-template", "p3-ate", "p3-clmm", "p3-mmpolish"]
LAYOUT_CAP = 1000

def nodes(g):
    return g.get("n") or g["p"].get("n") or g["p"].get("nodes") or g.get("nodes")

def ranges(ids):
    out, s, prev = [], None, None
    for i in ids:
        if s is None:
            s = prev = i
            continue
        if i == prev + 1:
            prev = i
            continue
        out.append((s, prev))
        s = prev = i
    out.append((s, prev))
    return ", ".join(f"{a}-{b}" if b > a else f"{a}" for a, b in out)

def yaml_text(name, algorithms, graphs, topology, note):
    algos = "\n".join(f"  - {a}" for a in algorithms)
    return (f"# generated by gen_m5_full.py — do not hand-edit\n"
            f"name: {name}\n"
            f"algorithms:\n{algos}\n"
            f'graphs: "{graphs}"\n'
            f"topologies: [{topology}]\n"
            f"trials: 1\nwarmup: 0\ntimeout: 60.0\nseed: 4242\nworkers: 60\n"
            f"output_dir: results/{name}\n"
            f'note: "{note} | (instance, trial) pairing [CLI] | paper3 M5 full"\n')

def main():
    m = json.load(open(MANIFEST))
    for topo, (tag, cap) in TOPOS.items():
        elig = sorted(g["id"] for g in m["graphs"] if nodes(g) <= cap)
        small = sorted(g["id"] for g in m["graphs"] if nodes(g) <= min(cap, LAYOUT_CAP))
        for name, arms, ids, note in (
            (f"m5full_{tag}", MAIN_ARMS, elig,
             f"complete Ember library, n<={cap} pigeonhole-eligible ({len(elig)} graphs)"),
            # no duplicate minorminer arm: CLI seed derivation is BATCH-independent
            # (root:algorithm:graph:topology:trial), so layout rows cross-batch pair
            # against the main batch's minorminer rows exactly as validly as within
            # one batch — at the usual "(instance, trial) [CLI]" regime (derived
            # seeds are arm-salted, never shared across arms; errata 4.12.10).
            (f"m5full_{tag}_layout", ["minorminer-layout"], small,
             f"layout supplement, n<={LAYOUT_CAP} ({len(small)} graphs; layout "
             f"stage unwatchdogged on CLI — big-n excluded)"),
        ):
            path = os.path.join(HERE, f"{name}.yaml")
            with open(path, "w") as fh:
                fh.write(yaml_text(name, arms, ranges(ids), topo, note))
            print(f"{name}: {len(ids)} graphs -> {os.path.basename(path)}")

if __name__ == "__main__":
    main()
